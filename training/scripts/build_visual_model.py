#!/usr/bin/env python3
"""给自建动力学模型挂接独立外观；只读取本项目已归档的显示资产。"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET


TRAINING = Path(__file__).resolve().parents[1]
BASE = TRAINING / "models" / "duck_v0.xml"
VISUAL_DIR = TRAINING / "models" / "visual"
MANIFEST = VISUAL_DIR / "manifest.json"
OUTPUT = TRAINING / "models" / "duck_visual.xml"


def build() -> Path:
    """保留原模型动力学，只增加非碰撞、零质量的外观 geom。"""
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    if manifest["schema_version"] != 1:
        raise ValueError("Unsupported visual manifest version")
    root = ET.parse(BASE).getroot()
    root.set("model", "duck_visual")
    root.insert(0, ET.Comment(
        " Display-only derivative: Pollen Robotics Microduck visual meshes; "
        "CC BY-NC-SA attribution and changes in visual/SOURCE.md. "
        "Physics remains the project's duck_v0 model. Generated by "
        "training/scripts/build_visual_model.py; do not edit manually. "
    ))
    compiler = root.find("compiler")
    if compiler is None:
        raise ValueError("Base model has no compiler element")
    compiler.set("meshdir", "visual/assets")
    visual_settings = root.find("visual")
    if visual_settings is None:
        visual_settings = ET.SubElement(root, "visual")
    # 原始自建模型没有场景光；提高外观可读性，不改变物理参数。
    headlight = visual_settings.find("headlight")
    if headlight is None:
        headlight = ET.SubElement(visual_settings, "headlight")
    headlight.set("ambient", "0.25 0.25 0.25")
    headlight.set("diffuse", "0.5 0.5 0.5")
    headlight.set("specular", "0.12 0.12 0.12")
    bodies = {body.get("name"): body for body in root.findall(".//body")}
    if set(bodies) != set(manifest["body_bindings"]):
        raise ValueError("Base body names no longer match the visual manifest")
    parents = {
        child.get("name"): parent.get("name")
        for parent in root.findall(".//body") for child in parent.findall("body")
    }
    for name, binding in manifest["body_bindings"].items():
        body = bodies[name]
        if parents.get(name) != binding["parent"]:
            raise ValueError(f"Changed body parent: {name}")
        # 根的世界高度由自建模型决定；子 body 的局部坐标必须保持源挂接契约。
        if binding["parent"] is not None:
            for key in ("pos", "quat"):
                actual = [float(v) for v in body.get(key, "").split()]
                expected = binding[key]
                if len(actual) != len(expected) or any(
                    abs(a - b) > 1e-7 for a, b in zip(actual, expected)
                ):
                    raise ValueError(f"Changed body transform: {name}.{key}")

    if root.find("asset") is not None:
        raise ValueError("Base asset section needs an explicit merge before rebuilding")
    asset = ET.Element("asset")
    for mesh in manifest["meshes"]:
        file = VISUAL_DIR / "assets" / mesh["file"]
        if file.resolve().parent != (VISUAL_DIR / "assets").resolve():
            raise ValueError(f"Asset path leaves visual/assets: {file}")
        payload = file.read_bytes()
        if len(payload) != mesh["bytes"] or hashlib.sha256(payload).hexdigest() != mesh["sha256"]:
            raise ValueError(f"Changed or incomplete visual asset: {file}")
        ET.SubElement(asset, "mesh", name=mesh["name"], file=mesh["file"])
    for material in manifest["materials"]:
        ET.SubElement(asset, "material", **material)
    root.insert(list(root).index(root.find("worldbody")), asset)

    defaults = root.find("default")
    if defaults is None:
        defaults = ET.SubElement(root, "default")
    visual_default = ET.SubElement(defaults, "default", {"class": "duck_visual"})
    ET.SubElement(visual_default, "geom", type="mesh", contype="0", conaffinity="0",
                  group="2", density="0", mass="0")

    for body in bodies.values():
        for geom in body.findall("geom"):
            geom.set("group", "3")
    for geom in root.findall("worldbody/geom"):
        geom.set("group", "0")
    ET.SubElement(root.find("worldbody"), "light", name="display_key",
                  pos="0.3 -0.4 0.8", dir="-0.3 0.4 -0.8", directional="true",
                  diffuse="0.25 0.25 0.25", specular="0.12 0.12 0.12")
    for name, binding in manifest["body_bindings"].items():
        for index, attributes in enumerate(binding["visual_geoms"]):
            allowed = {"type", "pos", "quat", "mesh", "material", "rgba"}
            if not set(attributes) <= allowed:
                raise ValueError(f"Unexpected visual geom attributes: {name}")
            attributes = dict(attributes)
            attributes.update(name=f"visual_{name}_{index:02d}", **{
                "class": "duck_visual", "contype": "0", "conaffinity": "0",
                "group": "2", "density": "0", "mass": "0",
            })
            ET.SubElement(bodies[name], "geom", attributes)

    ET.indent(root, space="  ")
    ET.ElementTree(root).write(OUTPUT, encoding="utf-8", xml_declaration=True)
    with OUTPUT.open("a", encoding="utf-8") as stream:
        stream.write("\n")
    return OUTPUT


if __name__ == "__main__":
    print(build())
